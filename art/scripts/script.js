const grid = document.getElementById("art-grid");
const msg = document.getElementById("JS-disclaimer");
if (msg) msg.remove();

artworks.forEach(a => {
	const ArtworkLarge = `artwork/${a.file}`
	
	const extensionPos = a.file.lastIndexOf(".");
	const fileNoExt = a.file.slice(0, extensionPos);
	
	const ArtworkSmall = `thumbnail/${fileNoExt}.webp`;

  const entry = document.createElement("div");

  entry.className = "div-art-entry";
  entry.dataset.img = ArtworkLarge;
	entry.dataset.thumbnail = ArtworkSmall;
  entry.dataset.title = a.title;
  entry.dataset.desc = a.desc;

  entry.innerHTML = `
    <div>
      <img src="${ArtworkSmall}" alt="">
    </div>
    <h2 class="unselectable">${a.title}</h2>
  `;

  grid.appendChild(entry);
});